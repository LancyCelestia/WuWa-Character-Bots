def search_dishes(keyword: str) -> list[Dish]:
    """按名称/食材模糊匹配（菜谱查询用）。"""
    needle = (keyword or "").strip().casefold()
    if not needle:
        return []
    return [
        dish
        for dish in DISHES
        if needle in dish.name.casefold()
        or needle in dish.materials.casefold()
    ]


