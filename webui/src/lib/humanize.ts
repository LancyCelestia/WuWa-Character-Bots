// 界面文案的「英文 → 中文白话」**唯一出口**（F 席）。
//
// 用户原话：「所有英文变量名、英文参数名、英文枚举值，在界面上一律换成中文白话」。
// 这个模块只做三件事，不做第四件：
//   ① `configTitleFor` / `displayTitle`：把 `BOT_LLM_AIPRC_ENABLED` 这类键推导成中文标题；
//   ② `humanizeEnum`：把 `true/half/hour/compact` 这类**枚举值**收成中文（全站同一张表，
//      禁止每页各写一套——那是第二真身）；
//   ③ `fieldLabel`：把后端 DTO 的 JSON 字段名（`model_id`、`health_state`）收成中文，
//      给「模型与渠道」「布局编辑器」那种 `Object.entries` 直出段用。
//
// 🔴 边界与诚实口径：
//   · **业务专名不硬译**。`Tavily`/`Gemini`/`守岸人` 这类名字猜错比不译更糟，所以原样保留，
//     但**中文主语必须在**（N2）。这一档单独计数，绝不混进「翻译成功」里凑数。
//   · **已是中文的标题一律不碰**。再拼一遍就是新的假中文——这正是本波要清掉的那种形态。
//   · **无从翻译的键诚实降级**（N3），给通用中文主语，不编一个像模像样的错词。
//
// 零运行时依赖（只 `import type` 也不做），故 `node --test` 可直跑。

