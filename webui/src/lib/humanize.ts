const CJK = /[\u4e00-\u9fff]/;
const HAS_LATIN = /[A-Za-z]/;

/** 一个 token 的译法。返回 null＝这个词表里没有，调用方负责诚实降级。 */
function translateToken(token: string): { text: string; latin: boolean } | null {
  const word = token.toLowerCase();
  if (word in PROPER) return { text: PROPER[word], latin: HAS_LATIN.test(PROPER[word]) };
  if (word in TOKEN) return { text: TOKEN[word], latin: HAS_LATIN.test(TOKEN[word]) };
  // 纯数字段（`1`、`256`）原样保留，它不是英文。
  if (/^[0-9]+$/.test(word)) return { text: word, latin: false };
  // `group1` / `black2` 这类带序号的：拆成词 + 序号。
  const numbered = /^([a-z]+)([0-9]+)$/.exec(word);
  if (numbered) {
    const base = translateToken(numbered[1]);
    if (base) return { text: `${base.text}${numbered[2]}`, latin: base.latin };
  }
  return null;
}

/** 拆键：去掉 `BOT_` 前缀，按下划线/连字符/点拆词。 */
function splitKey(key: string): string[] {
  const tokens = key
    .replace(/^bot_/i, '')
    .toLowerCase()
    .split(/[_\-.]+/)
    .filter(Boolean);
  // `API_KEY_AIPRC_GEMINI` 直译成「接口密钥 AI 优先级 Gemini」会被读成「一种密钥」。
  // head noun（密钥）挪到末尾才符合中文语序：AI 优先级 Gemini 接口密钥。
  const apiAt = tokens.indexOf('api');
  if (apiAt >= 0 && tokens[apiAt + 1] === 'key' && tokens.length > apiAt + 2) {
    const rest = [...tokens.slice(0, apiAt), ...tokens.slice(apiAt + 2)];
    return [...rest, 'api', 'key'];
  }
  return tokens;
}

/** 量纲在末位时用它来括号收尾（`…间隔（秒）`）。`kb` 在这里指千字节，不是知识库。 */
const UNIT_LABEL: Record<string, string> = { mb: 'MB', kb: 'KB' };

/** 词与词拼接：中文与中文之间不留空格，拉丁词/数字两侧留一个空格；相邻重复词只留一个。 */
function joinWords(parts: readonly { text: string; latin: boolean }[], separator = ''): string {
  let out = '';
  for (const part of parts) {
    if (out === '') {
      out = part.text;
      continue;
    }
    if (out.endsWith(part.text) || part.text.endsWith(out.slice(-part.text.length))) continue;
    const prevLatin = /[A-Za-z0-9]/.test(out.slice(-1));
    out += part.latin || prevLatin ? ` ${part.text}` : separator + part.text;
  }
  return out;
}

/**
 * 键名 → 中文标题 + 该结果属于哪一档（N1/N2/N3）。
 *
 * 组装顺序刻意如此，是为了让机械拼接读得顺：
 *   ① 普通词按原顺序译；② 界限词（max/min/limit）挪到末尾；③ 末位量纲进括号。
 */
export function deriveConfigTitle(key: string): TitleDerivation {
  const tokens = splitKey(key);
  const words: { text: string; latin: boolean }[] = [];
  const bounds: string[] = [];
  let units: string[] = [];
  let unknownCount = 0;
  let translatedCount = 0;

  const lastIsUnit = tokens.length > 1 && UNIT_TOKENS.has(tokens[tokens.length - 1]);
  const prevIsPer = (index: number) => index > 0 && tokens[index - 1] === 'per';

  tokens.forEach((token, index) => {
    // `on_startup` 是「启动时」，不是「开启 + 启动」。
    if (token === 'on' && tokens[index + 1] === 'startup') return;
    if (BOUND_TOKENS.has(token)) {
      bounds.push(TOKEN[token] ?? '界限');
      translatedCount += 1;
      return;
    }
    if (lastIsUnit && index === tokens.length - 1 && !prevIsPer(index)) {
      const unit = translateToken(token);
      if (unit) {
        units = [UNIT_LABEL[token] ?? unit.text];
        translatedCount += 1;
        return;
      }
    }
    const translated = translateToken(token);
    if (!translated) {
      unknownCount += 1;
      words.push({ text: token.charAt(0).toUpperCase() + token.slice(1), latin: true });
      return;
    }
    translatedCount += 1;
    words.push(translated);
  });

  const subject = joinWords(words);
  const withBounds = [subject, bounds.join('')].filter(Boolean).join('');
  const body = units.length && withBounds ? `${withBounds}（${units.join('')}）` : withBounds || units.join('');

  if (translatedCount === 0 || !CJK.test(body)) {
    // 一个中文词都没译出来。**不把原键塞进标题**：配置行本来就单独渲染着原键，
    // 塞进去只会在标题里多一串下划线，反而更像变量名。
    return { title: UNTRANSLATABLE_SUBJECT, kind: 'N3' };
  }
  return { title: body, kind: HAS_LATIN.test(body) || unknownCount > 0 ? 'N2' : 'N1' };
}

/** 键名 → 中文标题（N1/N2 都会给可读中文主语；N3 给通用主语 + 原键）。 */
export function configTitleFor(key: string): string {
  return deriveConfigTitle(key).title;
}

/**
 * 标题呈现的唯一裁决点。
 *
 * - `humanWritten`（T1 手写层）→ 一个字都不动：人手写的中文说明比任何推导都准。
 * - 标题本来就没有英文 → 不动（把中文再拼一遍＝制造新的假中文，正是本波要清的病）。
 * - 其余（T2/T3 的机械拼词）→ 按**键**重推，不信那个被切词切乱的旧标题。
 */
export function displayTitle(key: string, curated: string, humanWritten: boolean): string {
  if (humanWritten) return curated;
  if (!HAS_LATIN.test(curated)) return curated;
  return configTitleFor(key);
}

/** 枚举值 → 中文白话。全站共用这一处（简报第四条：不许每页各写一套）。 */
export function humanizeEnum(value: unknown): string {
  if (value === null || value === undefined) return '—';
  if (typeof value === 'boolean') return value ? '开启' : '关闭';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '—';
  if (typeof value !== 'string') return String(value);

  const raw = value.trim();
  if (raw === '') return '—';
  if (CJK.test(raw)) return raw; // 已经是中文：不二次拼
  const lower = raw.toLowerCase();
  if (lower in VALUE) return VALUE[lower];
  // 复合值（`partially_available`）逐词译；译不动就原样返回，不编。
  if (lower.includes('_') || lower.includes('-')) {
    const parts = lower.split(/[_-]+/).filter(Boolean).map((part) => VALUE[part] ?? translateToken(part)?.text);
    if (parts.length > 0 && parts.every((part): part is string => Boolean(part) && CJK.test(part))) {
      return parts.join('');
    }
  }
  return raw;
}

/** 后端 DTO 的字段名 → 中文标签（模型页、布局编辑器那种直出段用）。 */
export function fieldLabel(name: string): string {
  if (!HAS_LATIN.test(name)) return name;
  const parts = name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2') // camelCase 也拆开
    .toLowerCase()
    .split(/[_\-.]+/)
    .filter(Boolean);
  const words: { text: string; latin: boolean }[] = [];
  for (const part of parts) {
    const translated = translateToken(part);
    words.push(translated ?? { text: part.charAt(0).toUpperCase() + part.slice(1), latin: true });
  }
  const out = joinWords(words);
  return out || name;
}
